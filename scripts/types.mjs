// Generates dist/types from custom-elements.json:
//   index.d.ts  the functions exported beside an element (toast, confirm)
//               first, then one interface per element, its event map typed
//               with each event's `detail`, and HTMLElementTagNameMap
//   react.d.ts  JSX.IntrinsicElements for React 18 and 19
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const manifest = JSON.parse(
  await readFile(new URL('../custom-elements.json', import.meta.url), 'utf8')
);

const elements = [];
for (const mod of manifest.modules) {
  for (const decl of mod.declarations || []) {
    if (decl.kind === 'class' && decl.tagName)
      elements.push({ ...decl, path: mod.path });
  }
}
elements.sort((a, b) => a.tagName.localeCompare(b.tagName));

// The functions a module exports beside the element it defines: `toast` of
// the toaster, `confirm` of the alert dialog. Helpers of modules that define
// no element are internal, though the bundle exports them.
const functions = [];
for (const mod of manifest.modules) {
  const declarations = mod.declarations || [];
  if (!declarations.some((decl) => decl.kind === 'class' && decl.tagName))
    continue;
  for (const decl of declarations) {
    const exported = (mod.exports || []).some(
      (entry) => entry.kind === 'js' && entry.name === decl.name
    );
    if (decl.kind === 'function' && exported) functions.push(decl);
  }
}
functions.sort((a, b) => a.name.localeCompare(b.name));

// Names HTMLElement already types; redeclaring them breaks `extends`.
const NATIVE = new Set([
  'focus',
  'blur',
  'click',
  'remove',
  'title',
  'hidden',
  'id',
  'slot',
  'role',
  'lang',
  'dir',
  'tabIndex',
  'draggable',
  'inert',
  'translate',
  'style',
  'popover',
  'attachInternals',
  'contains',
  'append',
  'prepend',
  'toggleAttribute',
  'scroll',
  'scrollTo',
  'animate'
]);
const KNOWN_TYPES = new Set([
  'Array',
  'Record',
  'Date',
  'Element',
  'HTMLElement',
  'Node',
  'File',
  'FileList',
  'FormData',
  'DocumentFragment',
  'Map',
  'Set',
  'Promise',
  'Intl',
  'NumberFormatOptions',
  'DateTimeFormatOptions'
]);
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const tsType = (t) => {
  const text = (t?.text || 'string').trim();
  if (text === 'boolean' || text === 'number' || text === 'string') return text;
  if (/^('[^']*'\s*\|\s*)*'[^']*'$/.test(text)) return text;
  if (!/^[\w\s|'"<>[\]{}:,.?()=&-]+$/.test(text)) return 'string';
  // A type named in JSDoc that the declaration file cannot see becomes any.
  return text.replace(/\b[A-Z]\w*\b/g, (name) =>
    KNOWN_TYPES.has(name) ? name : 'any'
  );
};
// The type of an event's `detail`, written in its JSDoc as
// `@fires {{ value: string }} punica-change - ...`; any when it has none.
const detailType = (event) => {
  const text = event.type?.text?.trim();
  if (!text) return 'any';
  const type = tsType(event.type);
  return type === 'string' && text !== 'string' ? 'any' : type;
};
const doc = (text, indent = '  ') =>
  text
    ? `${indent}/** ${String(text)
        .replace(/\*\//g, '* /')
        .replace(/\s+/g, ' ')
        .trim()} */\n`
    : '';

/**
 * The properties a module's `static properties` gives a default (`default: ''`, `default: 'button'`): the element
 * holds such a value from the start, so its type is not nullable. A default of `null` or `undefined` keeps it nullable.
 * The manifest does not carry defaults, so they are read from the source.
 * @param {string} path the module's path in the package
 */
const defaultsOf = async (path) => {
  const source = await readFile(new URL(`../${path}`, import.meta.url), 'utf8');
  const block =
    /static properties = \{([\s\S]*?)\n {2}\};/.exec(source)?.[1] ?? '';
  const names = new Set();
  for (const m of block.matchAll(/^\s{4}(\w+):\s*\{([^}]*)\}/gm)) {
    const def = /\bdefault:\s*([^,}]+)/.exec(m[2])?.[1]?.trim();
    if (def !== undefined && def !== 'null' && def !== 'undefined')
      names.add(m[1]);
  }
  return names;
};

let index =
  '// Generated by scripts/types.mjs from custom-elements.json. Do not edit.\n\n';
let react =
  "// Generated by scripts/types.mjs from custom-elements.json. Do not edit.\nimport type * as React from 'react';\nimport type * as P from './index.js';\n\n";
const tagMap = [];
const jsx = [];

// The functions come first, so that a look at the top of the file finds them.
for (const fn of functions) {
  const params = (fn.parameters || [])
    .map(
      (p) =>
        `${p.name}${p.optional || p.default !== undefined ? '?' : ''}: ${
          p.type?.text ? tsType(p.type) : 'any'
        }`
    )
    .join(', ');
  const returns = fn.return?.type?.text ? tsType(fn.return.type) : 'void';

  index +=
    doc(fn.description, '') +
    `export declare function ${fn.name}(${params}): ${returns};\n\n`;
}


// `configure` is the one function of the core (core/element.js) a page calls;
// the manifest reads component modules only, so it is declared here.
index +=
  doc(
    "Sets a page's own defaults for elements, by tag: the values an element takes when its markup says nothing. `configure({ 'punica-button': { variant: 'outlined', size: 'small' } })`. Each value is a declared property of the element, written the first time the element connects unless the markup or a script already set it; call it before the elements are created. A later call for the same tag merges into the earlier one, and `null` takes a default away.",
    ''
  ) +
  'export declare function configure(defaults: { [K in keyof HTMLElementTagNameMap]?: { [P in keyof HTMLElementTagNameMap[K]]?: HTMLElementTagNameMap[K][P] | null } } & Record<string, Record<string, unknown>>): void;\n\n';


for (const el of elements) {
  const name = el.name;
  const attrs = el.attributes || [];
  const events = el.events || [];
  const propsOnly = (el.members || []).filter(
    (m) =>
      m.kind === 'field' &&
      m.privacy !== 'private' &&
      !m.static &&
      !attrs.some((a) => camel(a.name) === m.name) &&
      !NATIVE.has(m.name) &&
      m.description
  );
  const methods = (el.members || []).filter(
    (m) =>
      m.kind === 'method' &&
      m.privacy !== 'private' &&
      !m.name.startsWith('_') &&
      !m.name.startsWith('#') &&
      !NATIVE.has(m.name) &&
      ![
        'update',
        'connected',
        'disconnected',
        'firstUpdated',
        'formReset',
        'formRestore'
      ].includes(m.name)
  );

  index += doc(el.description, '') + `export interface ${name}Attributes {\n`;
  for (const a of attrs)
    index += doc(a.description) + `  '${a.name}'?: ${tsType(a.type)};\n`;
  index += '}\n\n';

  index += `export interface ${name}EventMap extends HTMLElementEventMap {\n`;
  for (const e of events)
    index +=
      doc(e.description) + `  '${e.name}': CustomEvent<${detailType(e)}>;\n`;
  index += '}\n\n';

  index +=
    doc(el.description, '') +
    `export interface ${name} extends HTMLElement {\n`;
  const defaults = await defaultsOf(el.path);
  for (const a of attrs.filter((a) => !NATIVE.has(camel(a.name)))) {
    // A property the element documents with a type of its own that cannot hold the attribute's (`@prop {string[]} value`
    // beside `@attr {string} value`: the attribute is the default written as text, the property holds the array). A
    // property that can also hold it (`string | string[] | null` of a select that may be multiple) keeps the
    // attribute's type, the single case code reads.
    const attrType = a.type?.text || 'string';
    const prop = (el.members || []).find(
      (m) =>
        m.kind === 'field' &&
        !m.static &&
        m.name === camel(a.name) &&
        m.description &&
        m.type?.text &&
        !m.type.text.split('|').map((part) => part.trim()).includes(attrType)
    );
    if (prop) {
      index += doc(prop.description) + `  ${prop.name}: ${tsType(prop.type)};\n`;
      continue;
    }
    const nullable =
      tsType(a.type) !== 'boolean' && !defaults.has(camel(a.name));
    index +=
      doc(a.description) +
      `  ${camel(a.name)}: ${tsType(a.type)}${nullable ? ' | null' : ''};\n`;
  }
  for (const p of propsOnly)
    index +=
      doc(p.description) +
      `  ${p.name}: ${
        p.type?.text && tsType(p.type) !== 'string' ? tsType(p.type) : 'any'
      };\n`;
  for (const m of methods) {
    const params = (m.parameters || [])
      .map((p) => `${p.name}${p.optional ? '?' : ''}: any`)
      .join(', ');
    index += doc(m.description) + `  ${m.name}(${params}): any;\n`;
  }
  // Every element has it (core/element.js): the manifest lists only a class's own members.
  index +=
    doc('Resolves after the pending update, if any, has run.') +
    `  readonly updateComplete: Promise<void>;\n`;
  index += `  addEventListener<K extends keyof ${name}EventMap>(type: K, listener: (this: ${name}, ev: ${name}EventMap[K]) => any, options?: boolean | AddEventListenerOptions): void;\n`;
  index += `  addEventListener(type: string, listener: EventListenerOrEventListenerObject, options?: boolean | AddEventListenerOptions): void;\n`;
  index += '}\n\n';

  tagMap.push(`    '${el.tagName}': ${name};`);
  // React 19 sets a prop as a property when the element has one and as an
  // attribute otherwise, so both spellings are typed.
  const loose = (t) => {
    const type = tsType(t);
    if (type === 'number') return 'number | string';
    if (type === 'boolean') return 'boolean';
    if (/^('\d+'\s*\|\s*)*'\d+'$/.test(type)) return `${type} | number`;
    return type;
  };
  const props = [];
  for (const a of attrs) {
    if (NATIVE.has(camel(a.name))) continue;
    props.push(`'${a.name}'?: ${loose(a.type)};`);
    if (camel(a.name) !== a.name)
      props.push(`${camel(a.name)}?: ${loose(a.type)};`);
  }
  for (const p of propsOnly) props.push(`${p.name}?: any;`);
  for (const e of events)
    props.push(`'on${e.name}'?: (event: CustomEvent<${detailType(e)}>) => void;`);
  const keys = [
    ...new Set(props.map((p) => p.slice(0, p.indexOf('?')).replace(/'/g, '')))
  ];
  const unique = keys.map((k) =>
    props.find((p) => p.replace(/'/g, '').startsWith(`${k}?`))
  );
  const base = `React.DetailedHTMLProps<React.HTMLAttributes<P.${name}>, P.${name}>`;
  jsx.push(
    `  '${el.tagName}': ${
      keys.length
        ? `Omit<${base}, ${keys.map((k) => `'${k}'`).join(' | ')}>`
        : base
    } & {\n    class?: string;\n${unique
      .map((p) => `    ${p}`)
      .join('\n')}\n  };`
  );
}

index += `declare global {\n  interface HTMLElementTagNameMap {\n${tagMap.join(
  '\n'
)}\n  }\n}\n`;
react += `type Elements = {\n${jsx.join(
  '\n'
)}\n};\n\ndeclare module 'react' {\n  namespace JSX {\n    interface IntrinsicElements extends Elements {}\n  }\n}\n\ndeclare global {\n  namespace JSX {\n    interface IntrinsicElements extends Elements {}\n  }\n}\n\nexport {};\n`;

await mkdir(new URL('../dist/types/', import.meta.url), { recursive: true });
await writeFile(new URL('../dist/types/index.d.ts', import.meta.url), index);
await writeFile(new URL('../dist/types/react.d.ts', import.meta.url), react);
console.log(
  `dist/types: ${elements.length} elements, ${functions.length} functions`
);
