// Writes src/index.js: one `export *` per component module.
// A module counts once it is an ES module on the 2.0 base class.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = new URL('../src/components/', import.meta.url).pathname;

export async function componentModules() {
  const out = [];
  for (const dir of (await readdir(root, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
    if (!dir.isDirectory()) continue;
    for (const file of (await readdir(join(root, dir.name))).sort()) {
      if (!file.endsWith('.js')) continue;
      const text = await readFile(join(root, dir.name, file), 'utf8');
      if (/^export\s+(class|function|const)\b/m.test(text)) {
        out.push(`components/${dir.name}/${file}`);
      }
    }
  }
  return out;
}

export async function writeBarrel() {
  const modules = await componentModules();
  const lines = [
    '// Generated by scripts/barrel.mjs. Do not edit.',
    "export * from './core/element.js';",
    "export * from './core/form.js';",
    "export * from './core/a11y.js';",
    "export * from './core/overlay.js';",
    ...modules.map((m) => `export * from './${m}';`),
    ''
  ];
  await writeFile(new URL('../src/index.js', import.meta.url), lines.join('\n'));
  return modules;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const modules = await writeBarrel();
  console.log(`src/index.js: ${modules.length} component modules`);
}
